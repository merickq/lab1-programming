import math  # Подключаем математический модуль для числа Пи и синуса

# Выводим шапку таблицы с выравниванием по правому краю
print(f"{'x':>8} {'sin(x)':>10}")
print("-" * 20)

# Цикл на 11 итераций (от i = 0 до i = 10 включительно)
for i in range(11):
    x = i * math.pi / 10  # Вычисляем текущий аргумент x с шагом pi/10
    y = math.sin(x)  # Вычисляем значение функции sin(x)
    # Выводим значения с точностью до 4 знаков после запятой
    print(f"{x:8.4f} {y:10.4f}")
