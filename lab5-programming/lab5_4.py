# Проверяем корректность ввода
try:
    n = int(input("Введите натуральное число (> 1): "))
except ValueError:
    print("Ошибка: необходимо ввести целое число.")
    exit()

# Краевой случай: числа <= 1 (0, 1, отрицательные) не имеют разложения на простые множители
if n <= 1:
    print("Разложение на простые множители возможно только для чисел больше 1.")
else:
    original = n  # Сохраняем исходное число для красивого вывода результата
    factors = []  # Список для хранения найденных простых множителей
    divisor = 2  # Начинаем проверку с наименьшего простого делителя (2)

    # Перебираем кандидатов в делители только до квадратного корня из текущего n
    while divisor * divisor <= n:
        # Пока число делится на текущий делитель без остатка
        while n % divisor == 0:
            factors.append(divisor)  # Сохраняем делитель
            n //= divisor  # Уменьшаем число, деля его нацело
        divisor += 1  # Переходим к следующему делителю

    # Если остаток больше 1, он является простым числом (включая случай, когда само исходное число простое)
    if n > 1:
        factors.append(n)

    # Формируем строку вида "360 = 2 x 2 x 2 x 3 x 3 x 5"
    print(f"{original} = {' x '.join(map(str, factors))}")
