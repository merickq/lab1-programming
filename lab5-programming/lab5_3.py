# Защита от некорректного ввода (нечисловых символов)
try:
    n = int(input("Введите N: "))
except ValueError:
    print("Ошибка: необходимо ввести целое число.")
    exit()

# Краевой случай: количество элементов последовательности должно быть больше 0
if n <= 0:
    print("Ошибка: N должно быть больше 0.")
else:
    # Задаём первые два числа ряда Фибоначчи
    a, b = 0, 1
    print(f"Первые {n} чисел Фибоначчи:")

    # Выполняем цикл ровно N раз
    for _ in range(n):
        print(a, end=" ")  # Выводим текущий элемент в одну строку через пробел
        a, b = b, a + b  # Одновременно обновляем пару значений (сдвиг на один шаг)
    print()  # Переводим курсор на новую строку
