# Проверяем корректность ввода (защита от ввода букв вместо числа)
try:
    n = int(input("Введите натуральное число: "))
except ValueError:
    print("Ошибка: необходимо ввести целое число.")
    exit()

# Краевой случай: числа <= 1 (0, 1, отрицательные) не могут быть совершенными (у 1 нет собственных делителей)
if n <= 1:
    print(f"{n} — не совершенное число")
else:
    divisors_sum = 1  # Единица всегда является собственным делителем для любого n > 1
    i = 2  # Начинаем поиск парных делителей с 2

    # Перебираем делители только до квадратного корня из n для ускорения алгоритма
    while i * i <= n:
        if n % i == 0:
            divisors_sum += i  # Прибавляем найденный делитель
            # Краевой случай: если n — полный квадрат (например, 4 или 25), не прибавляем корень дважды
            if i != n // i:
                divisors_sum += n // i  # Прибавляем парный делитель (n / i)
        i += 1

    # Число совершенное, если сумма всех его собственных делителей равна самому числу
    if divisors_sum == n:
        print(f"{n} — совершенное число")
    else:
        print(f"{n} — не совершенное число")
