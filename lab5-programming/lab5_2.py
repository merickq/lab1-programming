# Проверяем корректность ввода (защита от ввода букв или символов вместо числа)
try:
    n = int(input("Введите N: "))
except ValueError:
    print("Ошибка: необходимо ввести целое число.")
    exit()

# Краевой случай: факториал определён только для неотрицательных целых чисел
if n < 0:
    print("Ошибка: N должно быть неотрицательным числом (N >= 0).")
else:
    # Инициализируем переменные-накопители
    sum_numbers = 0  # Сумма чисел
    product = (
        1  # Произведение (при N = 0 цикл не выполнится и останется 1, так как 0! = 1)
    )
    sum_squares = 0  # Сумма квадратов

    # Перебираем все целые числа от 1 до N включительно
    for i in range(1, n + 1):
        sum_numbers += i  # Прибавляем текущее число
        product *= i  # Накапливаем произведение (факториал)
        sum_squares += i**2  # Прибавляем квадрат текущего числа

    # Выводим результаты вычислений
    print(f"Сумма: {sum_numbers}")
    print(f"Произведение (N!): {product}")
    print(f"Сумма квадратов: {sum_squares}")
