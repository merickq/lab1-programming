# Проверяем корректность ввода высоты фигур
try:
    n = int(input("Введите высоту фигур N (например, 5): "))
except ValueError:
    print("Ошибка: необходимо ввести целое число.")
    exit()

# Краевой случай: высота фигуры должна быть натуральным числом
if n <= 0:
    print("Ошибка: высота N должна быть больше 0.")
else:
    # 1. Прямоугольник (квадрат) N x N
    print("Прямоугольник:")
    for _ in range(n):
        print("*" * n)  # В каждой из n строк выводим n звёздочек

    # 2. Прямоугольный треугольник высотой N
    print("\nТреугольник:")
    for i in range(1, n + 1):
        print("*" * i)  # Номер строки i совпадает с количеством звёздочек

    # 3. Ёлочка (равнобедренный треугольник) высотой N
    print("\nЁлочка:")
    for i in range(1, n + 1):
        # (n - i) пробелов для центрирования + нечётное число звёздочек (2 * i - 1)
        print(" " * (n - i) + "*" * (2 * i - 1))

    # 4. Ромб (при N = 1 второй цикл не выполнится и корректно выведется одна звёздочка)
    print("\nРомб:")
    # Верхняя половина ромба (от 1 до N)
    for i in range(1, n + 1):
        print(" " * (n - i) + "*" * (2 * i - 1))
    # Нижняя перевёрнутая половина (от N - 1 вниз до 1)
    for i in range(n - 1, 0, -1):
        print(" " * (n - i) + "*" * (2 * i - 1))
