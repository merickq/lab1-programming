# Проверяем корректность ввода
try:
    n = int(input("Введите целое число: "))
except ValueError:
    print("Ошибка: необходимо ввести целое число.")
    exit()

# Краевой случай: число 0 состоит из одной цифры (0), её сумма и произведение равны 0
if n == 0:
    print("Количество цифр: 1")
    print("Сумма цифр: 0")
    print("Произведение цифр: 0")
    print("Перевёрнутое число: 0")
else:
    # Краевой случай: отрицательные числа обрабатываем по модулю, запоминая знак
    sign = -1 if n < 0 else 1
    temp = abs(n)

    count = 0  # Счётчик цифр
    total = 0  # Сумма цифр
    product = 1  # Произведение цифр
    reversed_num = 0  # Перевёрнутое число

    # Отсекаем по одной цифре справа налево, пока число не обнулится
    while temp > 0:
        digit = temp % 10  # Извлекаем последнюю цифру
        count += 1  # Увеличиваем счётчик цифр
        total += digit  # Прибавляем цифру к сумме
        product *= digit  # Умножаем произведение на цифру
        reversed_num = (
            reversed_num * 10 + digit
        )  # Дописываем цифру в конец перевёрнутого числа
        temp //= 10  # Отбрасываем обработанную последнюю цифру

    # Выводим результаты с учётом исходного знака числа
    print(f"Количество цифр: {count}")
    print(f"Сумма цифр: {total}")
    print(f"Произведение цифр: {product}")
    print(f"Перевёрнутое число: {sign * reversed_num}")
