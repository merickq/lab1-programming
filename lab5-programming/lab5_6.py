# Проверяем корректность ввода
try:
    n = int(input("Введите целое число: "))
except ValueError:
    print("Ошибка: необходимо ввести целое число.")
    exit()

# Краевой случай: отрицательные числа не являются палиндромами из-за знака минус впереди
if n < 0:
    print(f"{n} — не палиндром")
else:
    original = n  # Сохраняем исходное число для итогового сравнения
    reversed_num = 0  # Переменная для записи числа в обратном порядке
    temp = n  # Рабочая копия числа

    # Строим зеркальную копию числа (для n = 0 цикл не запустится и reversed_num останется 0)
    while temp > 0:
        digit = temp % 10  # Берём последнюю цифру
        reversed_num = reversed_num * 10 + digit  # Добавляем её в конец нового числа
        temp //= 10  # Убираем последнюю цифру из копии

    # Если исходное и перевёрнутое числа совпадают — это палиндром
    if original == reversed_num:
        print(f"{original} — палиндром")
    else:
        print(f"{original} — не палиндром")
