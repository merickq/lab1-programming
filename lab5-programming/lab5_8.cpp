#include <windows.h>

#include <iostream>
#include <limits>

int main() {
    // Настраиваем кодировку UTF-8 (65001) для консоли Windows
    SetConsoleCP(65001);
    SetConsoleOutputCP(65001);

    long long n;  // Используем long long для проверки крупных совершенных чисел
    std::cout << "Введите натуральное число: ";

    if (!(std::cin >> n)) {
        std::cout << "Ошибка: необходимо ввести целое число.\n";
        std::cin.clear();
    } else if (n <= 1) {
        // Краевой случай: 0, 1 и отрицательные числа не являются совершенными по определению
        std::cout << n << " — не совершенное число\n";
    } else {
        long long divisorsSum = 1;  // 1 — обязательный собственный делитель для любого n > 1

        // Условие i <= n / i эквивалентно i^2 <= n, но защищает от переполнения при больших
        // значениях long long
        for (long long i = 2; i <= n / i; ++i) {
            if (n % i == 0) {
                divisorsSum += i;  // Прибавляем первый делитель из пары
                // Краевой случай: для полных квадратов (4, 9, 16...) корень учитываем только один
                // раз
                if (i != n / i) {
                    divisorsSum += n / i;  // Прибавляем второй парный делитель
                }
            }
        }

        // Проверяем равенство суммы всех собственных делителей исходному числу
        if (divisorsSum == n) {
            std::cout << n << " — совершенное число\n";
        } else {
            std::cout << n << " — не совершенное число\n";
        }
    }

    // Очищаем остаток строки в буфере ввода и ждём нажатия Enter
    std::cout << "\nНажмите Enter для выхода...";
    std::cin.ignore(std::numeric_limits<std::streamsize>::max(), '\n');
    std::cin.get();
    return 0;
}