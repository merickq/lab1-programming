
#include <windows.h>  // Для настройки кодировки консоли

#include <iomanip>   // Для форматирования чисел
#include <iostream>  // Для ввода и вывода данных
#include <limits>    // Для очистки буфера ввода
using namespace std;

int main() {
    // Настраиваем кодировку для русского языка
    SetConsoleCP(65001);
    SetConsoleOutputCP(65001);

    // Объявляем переменные для координат и радиуса
    double x, y, R;

    // Запрашиваем координату X
    cout << "Введите координату X: ";
    cin >> x;

    // Запрашиваем координату Y
    cout << "Введите координату Y: ";
    cin >> y;

    // Запрашиваем радиус круга
    cout << "Введите радиус круга: ";
    cin >> R;

    // Настраиваем вывод до двух знаков после запятой
    cout << fixed << setprecision(2);

    // Проверяем корректность введённого радиуса
    if (R <= 0) {
        cout << "Ошибка: радиус должен быть больше нуля!" << endl;
    } else {
        // Вычисляем квадрат расстояния от точки до центра
        double distance = x * x + y * y;

        // Вычисляем квадрат радиуса
        double radius = R * R;

        // Проверяем положение точки
        if (distance < radius) {
            cout << "Точка находится внутри круга" << endl;
        } else if (distance == radius) {
            cout << "Точка находится на границе круга" << endl;
        } else {
            cout << "Точка находится вне круга" << endl;
        }
    }

    // Ожидаем нажатия Enter перед завершением
    cout << "\nНажмите Enter для выхода...";
    cin.ignore(numeric_limits<streamsize>::max(), '\n');
    cin.get();

    return 0;  // Завершение программы
}
